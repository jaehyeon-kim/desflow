import asyncio
import logging
import queue
import sys
import warnings
from pathlib import Path
from types import FrameType
from typing import Any, Literal, Optional

import orjson

from desflow.connectors.egress.base import BaseEgress, drop_reserved_keys

logger = logging.getLogger(__name__)

_PREFIXES = {"telemetry": "[TEL]", "event": "[EVT]", "label": "[LBL]"}


_FORMATS = ("log", "json")


# The folder of the desflow package, whose frames a warning skips
_PACKAGE = str(Path(__file__).resolve().parents[2])


def _caller_level() -> int:
    """The `stacklevel` of a warning that names the first line outside desflow,
    such as the script's `app.run()`, rather than a line of desflow itself."""
    level = 2
    frame: Optional[FrameType] = sys._getframe(2)
    while frame is not None and frame.f_code.co_filename.startswith(_PACKAGE):
        frame = frame.f_back
        level += 1
    return level


class ConsoleEgress(BaseEgress):
    """
    Local egress provider that outputs simulation data to the console.

    This connector serves as a debugging and local development tool. The `log`
    format logs each batch, distinguishing telemetry metrics from discrete events
    by prefixes. The `json` format writes each record to stdout as one JSON line,
    with its `stream_type`, for a pipe such as `jq`.
    """

    def __init__(self, format: Literal["log", "json"] = "log"):
        """
        Chooses how records are written.

        Args:
            format: `log` logs each batch at INFO level, one prefixed line per
                record. `json` writes one JSON line per record to stdout at any
                log level, because it is output, not a log.

        Raises:
            ValueError: If `format` is neither `log` nor `json`.
        """
        if format not in _FORMATS:
            raise ValueError(f"format must be log or json, got {format!r}")
        self.format = format

    # The console loads no library. It overrides this hook only because
    # setup_egress calls it before the run, which is when the warning must come
    def _load_libraries(self) -> None:
        """Warns, before the run starts, when the `log` format would print nothing.

        `setup_egress` calls this for each provider before the run. The console
        imports no library, so it uses the call to check its logger. The warning is
        a Python warning, not a log record: the `desflow` logger has a
        `NullHandler`, so with no logging set up a log record goes nowhere, and a
        script run with `python FILE` would print nothing at all. Python prints a
        warning on stderr unless its filters hide it. `desflow run` sets up logging
        at INFO, so a blueprint run gets no warning.
        """
        if self.format == "log" and not logger.isEnabledFor(logging.INFO):
            warnings.warn(
                "ConsoleEgress writes each batch with logging at INFO, which is not "
                'enabled, so it prints nothing. Use ConsoleEgress(format="json"), or '
                "call logging.basicConfig(level=logging.INFO) before the run.",
                stacklevel=_caller_level(),
            )

    def _shown(self, record: dict, shown: Optional[dict] = None) -> Any:
        """Returns what a record is written as: the record, or `shown` in its place,
        or only its value when the entry has `envelope` off. A ground-truth record is
        always written whole."""
        if not self.envelope and record.get("stream_type") != "label":
            return record.get("value")
        return record if shown is None else shown

    async def run(self, egress_queue: queue.Queue) -> None:
        """
        Continuously polls the egress queue and writes each batch.

        This method implements an asynchronous polling loop. It extracts batches
        from the internal queue. With the `json` format it writes each batch to
        stdout in one write, one JSON line per record as published. With the
        `log` format it writes each batch with one log call at INFO
        level, one line per record, each line starting with a prefix:
        - [TEL]: Telemetry data (e.g., resource utilization, queue lengths).
        - [EVT]: Event data (e.g., task lifecycle transitions).
        - [LBL]: Ground-truth records, on a sink added with `when: labels`.

        One call per batch rather than per record costs far less (issue #24), so
        the logging format's prefix, such as the time and level, appears on the
        first line of each batch only.

        Args:
            egress_queue: A thread-safe queue containing lists of dictionaries
                (batches) generated by the EgressMixIn.

        Note:
            If the queue is empty, the method yields control to the asyncio
            event loop for a short duration to prevent CPU pinning.
        """
        while True:
            try:
                # Receive a batch (list) of messages
                batch = egress_queue.get_nowait()
            except queue.Empty:
                # Yield to the event loop
                await asyncio.sleep(0.1)
                continue
            if not batch:
                continue
            if self.format == "json":
                # sys.stdout is read at each write, so a caller that replaces it,
                # such as a test runner, receives the lines
                batch = drop_reserved_keys(batch, self)
                try:
                    text = "".join(
                        orjson.dumps(self._shown(r)).decode() + "\n" for r in batch
                    )
                except Exception as exc:
                    # A batch that cannot be encoded is logged, and the sink goes on
                    logger.error(f"Console: batch not printed: {exc}")
                    continue
                sys.stdout.write(text)
                sys.stdout.flush()
                continue
            if not logger.isEnabledFor(logging.INFO):
                continue
            batch = drop_reserved_keys(batch, self)
            # Each line is the record without its stream type, which the prefix
            # names. The record is not altered: every egress provider is handed the
            # same dictionary objects, so removing a key here would also remove it
            # from what another attached sink writes.
            lines = [
                f"{_PREFIXES.get(data.get('stream_type', 'unknown'), '[EVT]')} "
                f"{self._shown(data, {k: v for k, v in data.items() if k != 'stream_type'})}"
                for data in batch
            ]
            logger.info("\n".join(lines))
