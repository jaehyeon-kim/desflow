import asyncio
import logging
import queue
from typing import Any

import orjson
import redis.asyncio as redis

from desflow.connectors.egress.base import BaseEgress, drop_reserved_keys

logger = logging.getLogger(__name__)


class RedisEgress(BaseEgress):
    """
    High-throughput asynchronous egress provider for streaming simulation data to Redis.

    This connector utilizes `redis.asyncio` for asynchronous I/O and publishes batched
    simulation results (events and telemetry) to Redis Streams (`XADD`) for real-time consumers.

    By default, it uses a unified stream, but supports dynamic stream multiplexing
    by reading the `__stream__` key from the data payloads.

    Attributes:
        url (str): The connection URL for the Redis server (e.g., redis://127.0.0.1:6379/0).
        stream_name (str): The default target Redis Stream name.
        client (redis.Redis | None): The underlying redis-py asynchronous client instance.
        **kwargs: Additional configuration dictionary passed to `redis.from_url`.
    """

    def __init__(self, url: str, stream_name: str = "simulation_data", **kwargs: Any):
        """
        Initializes the RedisEgress with topic and connection settings.

        Args:
            url: Redis connection URL (e.g., redis://127.0.0.1:6379/0).
            stream_name: Target Redis Stream name.
            **kwargs: Additional arguments for `redis.from_url`.
        """
        self.url = url
        self.stream_name = stream_name
        self.kwargs = kwargs
        self.client: redis.Redis | None = None

    async def _init_client(self) -> None:
        if self.client is None:
            self.client = redis.from_url(self.url, **self.kwargs)
            logger.info(f"RedisEgress connected to stream '{self.stream_name}'")

    async def run(self, egress_queue: queue.Queue) -> None:
        """
        The main execution loop that consumes the egress queue and publishes to Redis.

        This method maintains a connection to Redis and uses pipeline (`XADD`)
        commands to insert batches of data efficiently. A `__stream__` that is not
        text is warned about and ignored. A `TypeError` from redis-py, which refuses
        a keyword setting such as a misspelt `socket_timeout` when it makes the
        connection, ends the task, because no wait fixes it. Any other error is
        logged and the sink goes on with the next batch.

        Args:
            egress_queue: A thread-safe queue containing lists of dictionaries
                or Pydantic models generated by the EgressMixIn.
        """
        try:
            await self._init_client()
            await self._write_forever(egress_queue)
        finally:
            await self._close_client()

    def _warn_stream_field(self, chosen: Any) -> None:
        """Warns once that `__stream__` held something other than a stream name."""
        if not self.__dict__.get("_stream_field_warned"):
            self._stream_field_warned = True
            logger.warning(
                "RedisEgress ignores __stream__ %r: it must be the name of a stream, "
                "so the record goes to the stream %s.",
                chosen,
                self.stream_name,
            )

    async def _close_client(self) -> None:
        """Closes the client and forgets it, so the next run makes its own in its own
        event loop."""
        client, self.client = self.client, None
        if client is not None:
            await client.aclose()

    async def _write_forever(self, egress_queue: queue.Queue) -> None:
        """Publishes the batches of the queue until the task is cancelled."""
        assert self.client is not None
        while True:
            publishing = False
            try:
                batch = egress_queue.get_nowait()
                if not batch:
                    continue

                with self._writing():
                    # Redis routes by __stream__, and writes no other reserved key
                    batch = drop_reserved_keys(batch, self, keep=("__stream__",))
                    pipe = self.client.pipeline()
                    count = 0
                    for item in batch:
                        # Multi-stream multiplexing. `item` is an EventPayload or
                        # TelemetryPayload dict, and the caller's own data sits under
                        # `value`, so `__stream__` is looked for there first. Reading only
                        # the top level found nothing, because publish_event never puts it
                        # there, so every record went to the default stream and the
                        # routing silently did nothing. PostgresEgress unwraps the same
                        # way for `__table__`, which is why table routing always worked.
                        value = item.get("value")
                        nested = value if isinstance(value, dict) else {}
                        # A null or empty `__stream__` is no route
                        target = nested.get("__stream__") or item.get("__stream__")
                        if target is not None and type(target) is not str:
                            # redis-py refuses a name that is not text only when the
                            # pipeline runs, which would lose the whole batch
                            self._warn_stream_field(target)
                            target = None
                        target = target or self.stream_name

                        item_copy = item.copy()
                        item_copy.pop("__stream__", None)
                        if "__stream__" in nested:
                            item_copy["value"] = {
                                k: v for k, v in nested.items() if k != "__stream__"
                            }

                        # Redis Streams expect a dict of string fields.
                        # We serialize the entire item into a single 'payload' field.
                        # With envelope off the payload field holds the event's value
                        # alone, whatever its type.
                        body = (
                            item_copy.get("value")
                            if not self.envelope and item.get("stream_type") != "label"
                            else item_copy
                        )
                        try:
                            payload = orjson.dumps(body).decode("utf-8")
                        except TypeError as error:
                            # A record JSON cannot hold costs only itself, as in
                            # the Kafka and JSONL sinks
                            logger.warning(
                                f"RedisEgress skipped the record with key "
                                f"{item.get('key')}: it cannot be encoded as JSON: "
                                f"{error}"
                            )
                            continue
                        pipe.xadd(target, {"payload": payload})
                        count += 1

                    if count > 0:
                        publishing = True
                        await pipe.execute()
                    logger.debug(f"Inserted {count} records into Redis Streams")

            except queue.Empty:
                await asyncio.sleep(0.1)
            except Exception as e:
                if publishing and isinstance(e, TypeError):
                    # redis-py refused a keyword setting, such as a misspelt
                    # `socket_timeout`, when it made the connection: no wait fixes it
                    raise
                logger.error(f"Error publishing batch to Redis: {e}")
                service_unavailable = isinstance(
                    e, (OSError, redis.ConnectionError, redis.TimeoutError)
                )
                if not self._drop_backlog(
                    egress_queue, "RedisEgress", service_unavailable
                ):
                    await asyncio.sleep(1)
